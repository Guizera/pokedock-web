export function translate(language: SiteLanguage, source: string): string {
  return language === 'en' ? (english[source] ?? source) : source
}

export function initialLanguage(): SiteLanguage {
  try {
    const saved = window.localStorage.getItem('pokedock.language.v1')
    if (saved === 'pt' || saved === 'en') return saved
  } catch { /* Browser storage may be unavailable. */ }
  return window.navigator.language.toLowerCase().startsWith('pt') ? 'pt' : 'en'
}
